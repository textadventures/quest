//
// Cloudflare Pages silently honours only the first 100 rules in a
// _redirects file - rules beyond that are dropped with no error, which is
// how ~585 of these came to be dead in production without anyone noticing.
// Astro emits one static HTML page per entry instead (meta refresh +
// canonical + noindex), so there is no rule limit, and Pagefind skips them.
//
